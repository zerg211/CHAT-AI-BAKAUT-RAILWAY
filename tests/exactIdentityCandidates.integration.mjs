import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
const target=new URL(process.env.DATABASE_URL||'file:///missing');
assert.ok(['127.0.0.1','localhost','[::1]'].includes(target.hostname)&&target.pathname.startsWith('/bakaut_acceptance_'));
process.env.NODE_ENV='test';
const {pool}=await import('../src/db/pool.ts');
const {ProductRepository}=await import('../src/db/repositories.ts');
const {AgentManagerOrchestrator}=await import('../src/ai/agentManagerOrchestrator.ts');
const {extractEvidenceInput}=await import('../src/ai/evidenceInput.ts');
const repo=new ProductRepository(),key=randomUUID(),ids=[];
const make=async(name,specs,raw={})=>{const p=await repo.upsertProduct({name,sourceUrl:`https://fixtures.bakaut.invalid/${key}/${ids.length}`,specs,raw:{...raw,pageType:'product'}});ids.push(p.id);return p;};
try {
 const a=await make('Different equipment A',{'артикул':'0012345'},{supplierNamespace:'vendor-a',identifiers:[{namespace:'vendor-a',value:'A-001'}]});
 const b=await make('Different equipment B',{'артикул':'0012345'},{supplierNamespace:'vendor-b'});
 assert.equal(await repo.getProductByExactArticle('0012345'),null,'duplicate article is not an exact single identity');
 assert.deepEqual((await repo.getProductsByExactArticle('0012345')).map(p=>p.id).sort(),[a.id,b.id].sort());
 assert.deepEqual((await repo.getProductsByExactArticle('0012345','vendor-a')).map(p=>p.id),[a.id]);
 assert.deepEqual((await repo.getProductsByExactArticle('A-001','vendor-a')).map(p=>p.id),[a.id]);
 assert.equal((await repo.getProductsByExactArticle('A-001','vendor-b')).length,0);
 const orchestrator=new AgentManagerOrchestrator({},repo,{}, {}, async()=>{throw Error('exact identifiers must not call embeddings');});
 const retrieved=await orchestrator.searchCatalogProducts({query:'0012345',limit:1,identifiers:[{kind:'article',value:'0012345'}]});
 assert.equal(retrieved.vectorCount,0);
 assert.equal(retrieved.identityMatches[0].status,'ambiguous');
 assert.deepEqual(retrieved.identityMatches[0].productIds.sort(),[a.id,b.id].sort());
 assert.equal(retrieved.candidateTiers[0].tier,'preliminary_match');
 const alias=await make('Alias equipment',{'Артикул':'0009876',sku:'0009876'},{article:'0009876',identifiers:[{namespace:'vendor-c',value:'0009876'}]});
 assert.deepEqual((await repo.getProductsByExactArticle('0009876')).map(p=>p.id),[alias.id]);
 assert.equal((await repo.getProductsByExactArticle('9876')).length,0);
 const precise=await make('GX5000',{});
 const significantUrl=`https://fixtures.bakaut.invalid/${key}/representation?variant=left/`;
 const representation=await repo.upsertProduct({name:'Significant query fixture',sourceUrl:significantUrl,specs:{},raw:{pageType:'product'}});ids.push(representation.id);
 assert.equal((await repo.getProductBySourceUrl(significantUrl))?.id,representation.id);
 assert.equal(await repo.getProductBySourceUrl(significantUrl.slice(0,-1)),null,'query value slash is representation data');
 const canonicalUrl=`https://fixtures.bakaut.invalid/${key}/canonical-resource/`;
 const canonical=await repo.upsertProduct({name:'Canonical URL fixture',sourceUrl:canonicalUrl,specs:{},raw:{pageType:'product'}});ids.push(canonical.id);
 const tracked=extractEvidenceInput(`Проверьте ${canonicalUrl}?utm_source=acceptance&roistat_visit=fixture#details`,{firstPartyHosts:['fixtures.bakaut.invalid']});
 assert.equal(tracked.urls[0]?.canonical,canonicalUrl.slice(0,-1));
 assert.equal((await repo.getProductBySourceUrl(tracked.urls[0].canonical))?.id,canonical.id);
 assert.equal((await repo.getProductBySourceUrl(canonicalUrl.slice(0,-1)))?.id,canonical.id,'path trailing slash is equivalent');
 for(let i=0;i<25;i++)await make(`GX5000 accessory ${i}`,{text:'GX5000 compatibility'});
 assert.equal((await repo.searchProductsByModelTokens(['GX5000'],1))[0]?.id,precise.id,'exact name precedes newer substring distractors before LIMIT');
 console.log(JSON.stringify({status:'PASS',level:'I',checks:['Y07/duplicate-different-products','Y07/supplier-namespace','Y07/alias-one-product','I06/tracking-and-path-slash-equivalence','I06/semantic-query-preserved','E10/exact-before-limit']}));
} finally {await pool.query('DELETE FROM products WHERE id=ANY($1::uuid[])',[ids]);await pool.end();}
